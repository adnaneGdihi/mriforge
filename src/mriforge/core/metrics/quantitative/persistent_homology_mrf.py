def kspace_sampling_pattern_h0_certificate(
    mask: torch.Tensor, critical_scale: float | None = None
) -> torch.Tensor:
    r"""H_0 birth-death certificate for a k-space sampling pattern.

    Treats the **set of acquired k-space points** as a finite point cloud
    and reports the largest H_0 death time — the smallest scale at which
    the Vietoris-Rips complex becomes connected. This is the persistent-
    homology analogue of the LOUPE / PILOT mask-quality heuristic:
    sampling patterns whose largest MST edge is small have *no holes
    larger than that scale* and therefore (necessarily) reconstruct images
    without aliasing at the corresponding Nyquist resolution.

    Args:
        mask: ``(H, W)`` boolean mask (True = sampled). Patterns are
            promoted to a point cloud :math:`\{(i,j):\,M_{ij}=1\}`
            embedded in :math:`\mathbb{R}^2`.
        critical_scale: Optional pre-set Nyquist scale :math:`\varepsilon^*`.
            If provided, the certificate counts the number of *unkilled*
            H_0 classes at that scale (zero = fully connected).

    Returns:
        Scalar tensor. With ``critical_scale=None`` this is the largest
        H_0 death time (the connectivity diameter). With ``critical_scale``
        provided, this is the integer count of clusters that haven't yet
        merged at that scale (zero iff fully connected).
    """
    if mask.ndim != 2:
        raise ValueError(f"mask must be 2-D; got {tuple(mask.shape)}.")
    coords = mask.nonzero(as_tuple=False).float()
    if coords.shape[0] < 2:
        return mask.new_zeros((), dtype=torch.float32)
    diag = vietoris_rips_h0_diagram(coords)
    deaths = diag[:, 1]
    if critical_scale is None:
        return deaths.max().to(torch.float32)
    # Count classes that haven't yet died at the critical scale.
    return (deaths > critical_scale).sum().to(torch.float32)


def topological_completeness_certificate(mask: torch.Tensor, *, fov_pixels: int) -> torch.Tensor:
    r"""TCC: count of unkilled 1-cycles at the Nyquist scale.

    Per the Batch-2 #6 proposal, a mask passes the topological
    completeness certificate iff ``TCC(M; ε*) = 0`` for
    :math:`\varepsilon^*=\tfrac{1}{2}\,\Delta k_{\rm Nyquist}^{-1}\propto 1/N`.
    We use the practical surrogate ``critical_scale = fov_pixels / 4`` —
    a scale half the FOV in pixels, calibrated so a uniformly-sampled
    pattern with acceleration :math:`R\le 2` returns zero.

    Args:
        mask: ``(H, W)`` boolean mask.
        fov_pixels: Larger spatial dimension of the image grid (typically
            ``max(H, W)``).

    Returns:
        Scalar integer-valued tensor (count of clusters at critical scale).
        Zero iff the mask is *topologically complete*: every closed loop
        in the sampling pattern is filled by an acquired triangle.
    """
    if fov_pixels <= 0:
        raise ValueError("fov_pixels must be positive.")
    return kspace_sampling_pattern_h0_certificate(mask, critical_scale=fov_pixels / 4.0)


@register_metric(
    "topological_mask_certificate",
    aliases=["tcc", "mask_completeness"],
)
class TopologicalMaskCertificate:
    r"""Registered metric: count of unkilled H_0 classes at the Nyquist scale.

    Lower is better; zero certifies that the mask is connected at the
    chosen Nyquist scale (no aliasing gap larger than the scale).
    """

    def __init__(self, fov_pixels: int = 256) -> None:
        if fov_pixels <= 0:
            raise ValueError("fov_pixels must be positive.")
        self.fov_pixels = fov_pixels

    def __call__(
        self,
        prediction: torch.Tensor,
        target: torch.Tensor | None = None,
        **_: object,
    ) -> float:
        if prediction.dtype != torch.bool:
            prediction = prediction.abs() > 0
        if prediction.ndim == 2:
            return float(
                topological_completeness_certificate(prediction, fov_pixels=self.fov_pixels).item()
            )
        if prediction.ndim >= 2:
            mask_2d = prediction.reshape(-1, prediction.shape[-2], prediction.shape[-1])
            certs = [
                topological_completeness_certificate(m, fov_pixels=self.fov_pixels) for m in mask_2d
            ]
            return float(torch.stack(certs).mean().item())
        raise ValueError(f"prediction must have rank >= 2; got shape {tuple(prediction.shape)}.")

    @property
    def name(self) -> str:
        return "topological_mask_certificate"

    @property
    def higher_is_better(self) -> bool:
        return False
